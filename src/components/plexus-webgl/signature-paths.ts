export interface SignaturePoint3D {
    x: number;
    y: number;
    z: number;
}

type CubicControlPoint = readonly [number, number, number];
type CubicStroke = readonly CubicControlPoint[];

const CURVE_STEPS = 12;

function sampleCubicStrokes(strokes: readonly CubicStroke[]): SignaturePoint3D[][] {
    return strokes.map((stroke) => {
        if ((stroke.length - 1) % 3 !== 0) {
            throw new Error('A cubic stroke must contain one start point and three points per segment.');
        }

        const path: SignaturePoint3D[] = [];
        for (let segment = 0; segment + 3 < stroke.length; segment += 3) {
            const [start, control1, control2, end] = stroke.slice(segment, segment + 4);
            const firstStep = segment === 0 ? 0 : 1;

            for (let step = firstStep; step <= CURVE_STEPS; step++) {
                const t = step / CURVE_STEPS;
                const inverseT = 1 - t;
                const startWeight = inverseT ** 3;
                const control1Weight = 3 * inverseT ** 2 * t;
                const control2Weight = 3 * inverseT * t ** 2;
                const endWeight = t ** 3;

                path.push({
                    x: start[0] * startWeight + control1[0] * control1Weight + control2[0] * control2Weight + end[0] * endWeight,
                    y: start[1] * startWeight + control1[1] * control1Weight + control2[1] * control2Weight + end[1] * endWeight,
                    z: start[2] * startWeight + control1[2] * control1Weight + control2[2] * control2Weight + end[2] * endWeight,
                });
            }
        }

        return path;
    });
}

